"""Database tables and queries for the RQ3 study (Part 2).

Raw facts only: scores such as e and g are recomputed at analysis time, so the
formula can change without rerunning anyone. Uses the same Postgres connection
helper as the RQ1 app (db.get_db), but its own tables, all prefixed rq3_.
"""

from __future__ import annotations

from typing import Any

PARTICIPANTS_TABLE = """
CREATE TABLE IF NOT EXISTS rq3_participants (
    id TEXT PRIMARY KEY,                 -- from the study link (?pid=...)
    consented_at TEXT NOT NULL,
    interest_json TEXT,                  -- {"food_drink": 4, ...}
    feed_order TEXT NOT NULL,            -- e.g. "BCA"
    completed_at TEXT,
    end_survey_json TEXT
)
"""

BLOCKS_TABLE = """
CREATE TABLE IF NOT EXISTS rq3_blocks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participant_id TEXT NOT NULL REFERENCES rq3_participants(id),
    block_number INTEGER NOT NULL,       -- 0 = practice, 1-3 = feeds
    feed TEXT NOT NULL,                  -- A, B, C, or practice
    feed_state_json TEXT NOT NULL,       -- engine state, so a refresh does not reset it
    started_at TEXT NOT NULL,
    ended_at TEXT,
    survey_json TEXT,
    UNIQUE (participant_id, block_number)
)
"""

IMPRESSIONS_TABLE = """
CREATE TABLE IF NOT EXISTS rq3_impressions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    block_id BIGINT NOT NULL REFERENCES rq3_blocks(id),
    position INTEGER NOT NULL,           -- order within the block, from 1
    clip_id TEXT NOT NULL,
    topic TEXT NOT NULL,
    previous_clip_id TEXT,
    similarity_to_previous DOUBLE PRECISION,
    run_position INTEGER NOT NULL,
    decision TEXT NOT NULL,              -- first, stay, switch, forced_switch
    forced_reason TEXT,
    stay_probability DOUBLE PRECISION,
    draw DOUBLE PRECISION,
    state_json TEXT NOT NULL,
    shown_at TEXT NOT NULL,
    UNIQUE (block_id, position)
)
"""

EVENTS_TABLE = """
CREATE TABLE IF NOT EXISTS rq3_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    impression_id BIGINT NOT NULL REFERENCES rq3_impressions(id),
    event_type TEXT NOT NULL,
    video_time DOUBLE PRECISION,
    client_wall_time TEXT,
    server_received_at TEXT NOT NULL,
    details_json TEXT
)
"""

SCHEMA_STATEMENTS = (PARTICIPANTS_TABLE, BLOCKS_TABLE, IMPRESSIONS_TABLE, EVENTS_TABLE)

# Events the player may send. Anything else is rejected.
EVENT_TYPES = frozenset(
    {
        "first_frame",  # real start time; load delay before it is not viewing time
        "swipe",  # main outcome: video time and loop count when they left
        "loop",  # the video restarted on its own
        "like",
        "unlike",
        "pause",
        "resume",
        "stall",  # buffering started
        "stall_end",
        "hidden",  # tab hidden or phone locked
        "visible",
        "error",  # failed load
    }
)


def init_schema(db: Any) -> None:
    """Create the RQ3 tables if they do not exist."""
    for statement in SCHEMA_STATEMENTS:
        db.execute(statement)
    db.commit()


