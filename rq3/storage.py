"""Postgres tables and queries for the RQ3 study.

Raw facts only: scores such as e and g are recomputed at analysis time, so the
formula can change without rerunning anyone. The engine state of each part is
saved after every decision, so a refresh or a server restart resumes exactly.

The database is chosen by RQ3_DATABASE_URL (never DATABASE_URL, which the RQ1
pilot's instructions export for its own live database). Every table is prefixed
rq3_ so it cannot collide with RQ1's tables.
"""

from __future__ import annotations

import itertools
import json
import os
from datetime import datetime, timezone
from typing import Any

import psycopg
from psycopg.rows import dict_row

DATABASE_URL_ENV = "RQ3_DATABASE_URL"
FEED_ORDERS = ["".join(order) for order in itertools.permutations("ABC")]
ORDER_LOCK_KEY = (31_003, 1)  # pg advisory lock: one feed-order assignment at a time

Connection = psycopg.Connection[dict[str, Any]]

PARTICIPANTS_TABLE = """
CREATE TABLE IF NOT EXISTS rq3_participants (
    id TEXT PRIMARY KEY,                 -- from the study link (?pid=...)
    created_at TEXT NOT NULL,
    feed_order TEXT NOT NULL,            -- e.g. "BCA"
    interest_json TEXT NOT NULL,         -- {"food_drink": 4, ...}
    videos_per_part INTEGER NOT NULL,
    device TEXT,                         -- browser user agent
    completed_at TEXT
)
"""

BLOCKS_TABLE = """
CREATE TABLE IF NOT EXISTS rq3_blocks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participant_id TEXT NOT NULL REFERENCES rq3_participants(id),
    block_number INTEGER NOT NULL,       -- 1-3 = the three feeds
    feed TEXT NOT NULL,                  -- A, B or C
    feed_state_json TEXT NOT NULL,       -- engine state after the latest decision
    started_at TEXT NOT NULL,
    ended_at TEXT,
    UNIQUE (participant_id, block_number)
)
"""

IMPRESSIONS_TABLE = """
CREATE TABLE IF NOT EXISTS rq3_impressions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    block_id BIGINT NOT NULL REFERENCES rq3_blocks(id),
    position INTEGER NOT NULL,           -- order within the block, from 1
    clip_id TEXT NOT NULL,
    topic TEXT NOT NULL,
    run_position INTEGER NOT NULL,
    decision TEXT NOT NULL,              -- first, stay, switch, forced_switch
    forced_reason TEXT,
    stay_probability DOUBLE PRECISION,
    draw DOUBLE PRECISION,
    previous_engagement DOUBLE PRECISION,
    state_json TEXT NOT NULL,            -- engine state the decision was made from
    shown_at TEXT NOT NULL,
    outcome_json TEXT,                   -- how the viewer left it, as the player reported
    outcome_at TEXT,
    UNIQUE (block_id, position)
)
"""

EVENTS_TABLE = """
CREATE TABLE IF NOT EXISTS rq3_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    impression_id BIGINT NOT NULL REFERENCES rq3_impressions(id),
    event_type TEXT NOT NULL,
    video_time DOUBLE PRECISION,
    client_wall_time TEXT,
    server_received_at TEXT NOT NULL,
    details_json TEXT
)
"""

SCHEMA_STATEMENTS = (PARTICIPANTS_TABLE, BLOCKS_TABLE, IMPRESSIONS_TABLE, EVENTS_TABLE)
TABLES = ("rq3_events", "rq3_impressions", "rq3_blocks", "rq3_participants")  # children first

# Events the player may send. Anything else is rejected.
EVENT_TYPES = frozenset(
    {
        "first_frame",  # real start time; load delay before it is not viewing time
        "swipe",  # main outcome: video time and loop count when they left
        "loop",  # the video restarted on its own
        "like",
        "unlike",
        "pause",
        "resume",
        "stall",  # buffering started
        "stall_end",
        "hidden",  # tab hidden or phone locked
        "visible",
        "error",  # failed load
    }
)


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


# --- Connections and schema -----------------------------------------------------------


def database_url() -> str:
    url = os.environ.get(DATABASE_URL_ENV)
    if not url:
        raise RuntimeError(f"{DATABASE_URL_ENV} is not set")
    return url


def connect(url: str) -> Connection:
    """An autocommit connection: group statements with `with db.transaction():`."""
    return psycopg.connect(url, row_factory=dict_row, autocommit=True)


def init_schema(db: Connection) -> None:
    """Create the RQ3 tables if they do not exist."""
    with db.transaction():
        for statement in SCHEMA_STATEMENTS:
            db.execute(statement)


def clear_all(db: Connection) -> None:
    """Delete every RQ3 row. For tests and local development only."""
    db.execute(f"TRUNCATE {', '.join(TABLES)} RESTART IDENTITY")


# --- Participants -------------------------------------------------------------------


def assign_feed_order(db: Connection) -> str:
    """The least-used of the 6 orders of A, B and C. Call inside the transaction that
    creates the participant: the lock makes concurrent sign-ups take turns."""
    db.execute("SELECT pg_advisory_xact_lock(%s, %s)", ORDER_LOCK_KEY)
    rows = db.execute("SELECT feed_order, COUNT(*) AS n FROM rq3_participants GROUP BY feed_order").fetchall()
    used = {row["feed_order"]: row["n"] for row in rows}
    return min(FEED_ORDERS, key=lambda order: (used.get(order, 0), FEED_ORDERS.index(order)))


def create_participant(
    db: Connection,
    participant_id: str,
    feed_order: str,
    interest: dict[str, int],
    videos_per_part: int,
    device: str | None,
) -> None:
    db.execute(
        """
        INSERT INTO rq3_participants (id, created_at, feed_order, interest_json, videos_per_part, device)
        VALUES (%s, %s, %s, %s, %s, %s)
        """,
        (participant_id, utc_now(), feed_order, json.dumps(interest), videos_per_part, device),
    )


def get_participant(db: Connection, participant_id: str, *, lock: bool = False) -> dict[str, Any] | None:
    """The participant row; `lock` holds it until the transaction ends, so two
    requests for the same participant (a double swipe) run one after the other."""
    suffix = " FOR UPDATE" if lock else ""
    row = db.execute(f"SELECT * FROM rq3_participants WHERE id = %s{suffix}", (participant_id,)).fetchone()
    if row is not None:
        row["interest"] = json.loads(row.pop("interest_json"))
    return row


def mark_completed(db: Connection, participant_id: str) -> None:
    db.execute("UPDATE rq3_participants SET completed_at = %s WHERE id = %s", (utc_now(), participant_id))


# --- Blocks (one per part) -----------------------------------------------------------


def start_block(db: Connection, participant_id: str, block_number: int, feed: str, state: dict) -> int:
    row = db.execute(
        """
        INSERT INTO rq3_blocks (participant_id, block_number, feed, feed_state_json, started_at)
        VALUES (%s, %s, %s, %s, %s)
        RETURNING id
        """,
        (participant_id, block_number, feed, json.dumps(state), utc_now()),
    ).fetchone()
    return row["id"]


def blocks_for(db: Connection, participant_id: str) -> list[dict[str, Any]]:
    rows = db.execute(
        "SELECT * FROM rq3_blocks WHERE participant_id = %s ORDER BY block_number", (participant_id,)
    ).fetchall()
    for row in rows:
        row["feed_state"] = json.loads(row.pop("feed_state_json"))
    return rows


def save_feed_state(db: Connection, block_id: int, state: dict) -> None:
    db.execute("UPDATE rq3_blocks SET feed_state_json = %s WHERE id = %s", (json.dumps(state), block_id))


def end_block(db: Connection, block_id: int) -> None:
    db.execute("UPDATE rq3_blocks SET ended_at = %s WHERE id = %s", (utc_now(), block_id))


# --- Impressions (one per video shown) ------------------------------------------------


def record_impression(db: Connection, block_id: int, position: int, decision: dict[str, Any]) -> int:
    row = db.execute(
        """
        INSERT INTO rq3_impressions
          (block_id, position, clip_id, topic, run_position, decision, forced_reason,
           stay_probability, draw, previous_engagement, state_json, shown_at)
        VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
        RETURNING id
        """,
        (
            block_id,
            position,
            decision["clip_id"],
            decision["topic"],
            decision["run_position"],
            decision["kind"],
            decision["forced_reason"],
            decision["stay_probability"],
            decision["draw"],
            decision["previous_engagement"],
            json.dumps(decision["state_snapshot"]),
            utc_now(),
        ),
    ).fetchone()
    return row["id"]


def impressions_for(db: Connection, block_id: int) -> list[dict[str, Any]]:
    rows = db.execute(
        "SELECT * FROM rq3_impressions WHERE block_id = %s ORDER BY position", (block_id,)
    ).fetchall()
    for row in rows:
        row["state"] = json.loads(row.pop("state_json"))
        outcome = row.pop("outcome_json")
        row["outcome"] = json.loads(outcome) if outcome else None
    return rows


def record_outcome(db: Connection, impression_id: int, outcome: dict[str, Any]) -> None:
    db.execute(
        "UPDATE rq3_impressions SET outcome_json = %s, outcome_at = %s WHERE id = %s",
        (json.dumps(outcome), utc_now(), impression_id),
    )


def impression_for_clip(db: Connection, participant_id: str, clip_id: str) -> int | None:
    """The impression where this participant was shown `clip_id`. Clips never repeat
    for a participant, so there is at most one."""
    row = db.execute(
        """
        SELECT i.id FROM rq3_impressions AS i
        JOIN rq3_blocks AS b ON b.id = i.block_id
        WHERE b.participant_id = %s AND i.clip_id = %s
        """,
        (participant_id, clip_id),
    ).fetchone()
    return row["id"] if row else None


# --- Events ------------------------------------------------------------------------------


def record_event(db: Connection, impression_id: int, event: dict[str, Any]) -> None:
    if event["event_type"] not in EVENT_TYPES:
        raise ValueError(f"Unknown event type: {event['event_type']}")
    db.execute(
        """
        INSERT INTO rq3_events
          (impression_id, event_type, video_time, client_wall_time, server_received_at, details_json)
        VALUES (%s, %s, %s, %s, %s, %s)
        """,
        (
            impression_id,
            event["event_type"],
            event.get("video_time"),
            event.get("client_wall_time"),
            utc_now(),
            json.dumps(event.get("details") or {}),
        ),
    )


def events_for(db: Connection, impression_id: int) -> list[dict[str, Any]]:
    rows = db.execute(
        """
        SELECT event_type, video_time, client_wall_time, server_received_at, details_json
        FROM rq3_events WHERE impression_id = %s ORDER BY id
        """,
        (impression_id,),
    ).fetchall()
    for row in rows:
        row["details"] = json.loads(row.pop("details_json") or "{}")
    return rows


# --- Admin -------------------------------------------------------------------------------


def list_participants(db: Connection) -> list[dict[str, Any]]:
    """One summary row per participant, newest first."""
    return db.execute(
        """
        SELECT p.id, p.created_at, p.completed_at, p.feed_order, p.videos_per_part,
               COUNT(DISTINCT b.id) AS parts_started,
               COUNT(DISTINCT b.id) FILTER (WHERE b.ended_at IS NOT NULL) AS parts_done,
               COUNT(i.id) AS videos_shown
        FROM rq3_participants AS p
        LEFT JOIN rq3_blocks AS b ON b.participant_id = p.id
        LEFT JOIN rq3_impressions AS i ON i.block_id = b.id
        GROUP BY p.id
        ORDER BY p.created_at DESC
        """
    ).fetchall()


def delete_participant(db: Connection, participant_id: str) -> bool:
    """Remove a participant and everything recorded for them. Returns whether they existed.
    Their feed order is freed, so order balancing counts only remaining participants."""
    with db.transaction():
        db.execute(
            """
            DELETE FROM rq3_events WHERE impression_id IN (
                SELECT i.id FROM rq3_impressions AS i JOIN rq3_blocks AS b ON b.id = i.block_id
                WHERE b.participant_id = %s)
            """,
            (participant_id,),
        )
        db.execute(
            "DELETE FROM rq3_impressions WHERE block_id IN (SELECT id FROM rq3_blocks WHERE participant_id = %s)",
            (participant_id,),
        )
        db.execute("DELETE FROM rq3_blocks WHERE participant_id = %s", (participant_id,))
        deleted = db.execute("DELETE FROM rq3_participants WHERE id = %s", (participant_id,)).rowcount
    return deleted > 0
