from __future__ import annotations

from typing import Any
import os
import psycopg
from psycopg.rows import dict_row
from flask import g

DATABASE_URL = os.environ.get("DATABASE_URL")

# sessions manages participant's state. Records a unique id, shuffled sequence of videos assigned to them
# and their current position within the video sequence to track their progress.
session_cmd = """
CREATE TABLE IF NOT EXISTS sessions (
    id TEXT PRIMARY KEY,
    trial_order_json TEXT NOT NULL,
    current_position INTEGER NOT NULL DEFAULT 0,
    started_at TEXT NOT NULL,
    completed_at TEXT
) """

# a specific video interaction within a participant's session. It links back to session_id in the sessions table.
# it stores the video url, assigned interaction mode (fixed_probe or free_swipe), and the planned probe schedule (probe_plan_json).
trials_cmd = """
CREATE TABLE IF NOT EXISTS trials (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id TEXT NOT NULL REFERENCES sessions(id),
    position INTEGER NOT NULL,
    video_id TEXT NOT NULL,
    video_title TEXT NOT NULL,
    video_url TEXT NOT NULL,
    interaction_mode TEXT NOT NULL,
    probe_plan_json TEXT NOT NULL,
    created_at TEXT NOT NULL,
    ended_at TEXT,
    UNIQUE(session_id, position)
)
"""

# response table captures participant's explicit decisions during fixed_probe trials. It logs the trial_id (from trials table)
# specific probe index (e.g., first probe, second probe) within the trial. It records the user's choice. 
response_cmd = """
CREATE TABLE IF NOT EXISTS responses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trial_id BIGINT NOT NULL REFERENCES trials(id),
    probe_index INTEGER NOT NULL,
    planned_probe_time DOUBLE PRECISION NOT NULL,
    probe_category TEXT NOT NULL,
    choice TEXT NOT NULL CHECK(choice IN ('continue', 'next')),
    submitted_at TEXT NOT NULL,
    UNIQUE(trial_id, probe_index)
)
"""

# append-only telemetry log. records video starts, ends, voluntary swipes
events_cmd = """
CREATE TABLE IF NOT EXISTS events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trial_id BIGINT NOT NULL REFERENCES trials(id),
    event_type TEXT NOT NULL,
    video_time DOUBLE PRECISION,
    client_wall_time TEXT,
    server_received_at TEXT NOT NULL,
    details_json TEXT
)
"""

SCHEMA_STATEMENTS = (session_cmd, trials_cmd, response_cmd, events_cmd,)

def get_db() -> psycopg.Connection[dict[str, Any]]:
    """Return one PostgreSQL connection for the current Flask request."""
    if "db" not in g:
        if not DATABASE_URL:
            raise RuntimeError("DATABASE_URL must be set to a PostgreSQL connection URL.")
        g.db = psycopg.connect(DATABASE_URL, row_factory=dict_row)
    return g.db

def close_db(_error: Exception | None) -> None:
    db = g.pop("db", None)
    if db is not None:
        db.close()

def init_db() -> None:
    """Create the study tables in a fresh PostgreSQL database."""
    db = get_db()
    for statement in SCHEMA_STATEMENTS:
        db.execute(statement)
    db.commit()
